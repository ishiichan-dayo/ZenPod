use sha1::{Digest, Sha1};
use std::num::Wrapping;

/// C の uint32_t と同じく 2^32 で回る整数
type W = Wrapping<u32>;

/// 署名の長さ (先頭 2 バイトは 03 00)
pub const HASHAB_LEN: usize = 57;
/// libgpod が渡す固定の乱数部
pub const HASHAB_RND: &[u8; 23] = b"ABCDEFGHIJKLMNOPQRSTUVW";
/// mhbd ヘッダ内の hashAB の位置
const HASHAB_OFFSET: usize = 0xAB;
/// mhbd の hashing_scheme (0x30) に入れる値 (libgpod の ITDB_CHECKSUM_HASHAB)
const HASHING_SCHEME_HASHAB: u16 = 3;

// ---------------- 共通 ----------------

fn load32_le(p: &[u8]) -> u32 {
    u32::from_le_bytes([p[0], p[1], p[2], p[3]])
}

fn store32_le(p: &mut [u8], value: u32) {
    p[..4].copy_from_slice(&value.to_le_bytes());
}

fn rol(value: W, count: u32) -> W {
    Wrapping(value.0.rotate_left(count))
}

// ---------------- calcHashAB.c ----------------

const PERMUTATION_32: [u8; 32] = [
    0x06, 0x18, 0x11, 0x07, 0x13, 0x0d, 0x0e, 0x09, 0x15, 0x1d, 0x02, 0x1f, 0x01, 0x04, 0x1c, 0x1a,
    0x10, 0x14, 0x0b, 0x1e, 0x03, 0x0a, 0x1b, 0x19, 0x05, 0x0f, 0x16, 0x00, 0x12, 0x17, 0x08, 0x0c,
];

/// 元コードは 56 個並べて先頭 55 個だけを使う (最後の 0x37 は使われない)
const PERMUTATION_56: [u8; 56] = [
    0x15, 0x1c, 0x06, 0x0c, 0x07, 0x1a, 0x05, 0x13, 0x08, 0x19, 0x03, 0x01, 0x2d, 0x1e, 0x10, 0x31,
    0x1d, 0x14, 0x28, 0x27, 0x35, 0x00, 0x2f, 0x1b, 0x26, 0x0b, 0x0e, 0x02, 0x23, 0x17, 0x24, 0x22,
    0x12, 0x1f, 0x20, 0x04, 0x29, 0x25, 0x21, 0x09, 0x18, 0x0d, 0x32, 0x0f, 0x11, 0x2e, 0x33, 0x2b,
    0x30, 0x2a, 0x36, 0x0a, 0x2c, 0x34, 0x16, 0x37,
];

/// hashAB 署名 (57 バイト) を計算する。
///
/// `sha1` は署名欄などを 0 にした iTunesDB 全体の SHA-1、`uuid` は FireWire GUID の 8 バイト、
/// `rnd` は乱数部 (libgpod は常に [`HASHAB_RND`] を渡す)。
pub fn calc_hashab(sha1: &[u8; 20], uuid: &[u8; 8], rnd: &[u8; 23]) -> [u8; 57] {
    let mut stage1_input = [0xc1u8; 80];
    for (d, s) in stage1_input[..8].iter_mut().zip(uuid) {
        *d = s.wrapping_mul(0xed);
    }
    for (d, s) in stage1_input[8..28].iter_mut().zip(sha1) {
        *d = s.wrapping_mul(0xed);
    }
    for (d, s) in stage1_input[28..51].iter_mut().zip(rnd) {
        *d = s.wrapping_mul(0xed);
    }

    let mut stage1_output = [0u8; 80];
    cipher_cbc(&STAGE1_PROFILE, &mut stage1_output, &stage1_input, STAGE1_INITIAL_CHAIN);
    let expanded = expand(&stage1_output[20..44], &stage1_output[..20]);
    let compression = reduce(&expanded);

    let stage2_input: [u8; 32] = std::array::from_fn(|i| stage1_output[44 + PERMUTATION_32[i] as usize]);
    let mut stage2_output = [0u8; 32];
    stage2_cipher(&mut stage2_output, &stage2_input, &compression);

    let mut target = [0u8; HASHAB_LEN];
    target[0] = 3;
    target[1] = 0;
    for (t, &source) in target[2..].iter_mut().zip(&PERMUTATION_56[..55]) {
        let source = source as usize;
        *t = if source < 23 { rnd[source] } else { stage2_output[source - 23].wrapping_mul(0x2d) };
    }
    target
}

/// シリアライズ済みの mhbd (iTunesDB / iTunesCDB のバイト列) に hashAB を書き込む。
///
/// libgpod の itdb_hashAB_write_hash と同じ手順:
/// hashing_scheme (0x30) を 3 にし、db_id (0x18)・hash58 (0x58)・hash72 (0x72)・hashAB (0xAB) を
/// 0 にした状態で全体の SHA-1 を取り、hashAB を書いてから db_id を戻す (hash58 / hash72 は 0 のまま)。
/// unk_0x32 は libgpod と同じく 0 にせず、そのままの値で SHA-1 に含める。
/// iTunesCDB の場合は圧縮後のバイト列 (ヘッダは非圧縮) に対して呼ぶ。
pub fn write_hashab(db: &mut [u8], uuid: &[u8; 8]) {
    let end = HASHAB_OFFSET + HASHAB_LEN;
    assert!(db.len() >= end && &db[0..4] == b"mhbd");
    assert!(load32_le(&db[4..8]) as usize >= end, "mhbd ヘッダが短く hashAB を書けない");

    db[0x30..0x32].copy_from_slice(&HASHING_SCHEME_HASHAB.to_le_bytes());
    let mut backup18 = [0u8; 8];
    backup18.copy_from_slice(&db[0x18..0x20]);

    db[0x18..0x20].fill(0);
    db[0x58..0x6C].fill(0);
    db[0x72..0xA0].fill(0);
    db[HASHAB_OFFSET..end].fill(0);

    let mut sha1 = [0u8; 20];
    sha1.copy_from_slice(&Sha1::digest(&*db));
    let hash = calc_hashab(&sha1, uuid, HASHAB_RND);
    db[HASHAB_OFFSET..end].copy_from_slice(&hash);
    db[0x18..0x20].copy_from_slice(&backup18);
}

// ---------------- cipher.c ----------------

/// AES-128 をテーブル化して難読化したブロック暗号 (CBC) の定数一式
struct CipherProfile {
    input_map: [u8; 256],
    final_map: [u8; 256],
    output_map: [u8; 256],
    round_base: [u8; 256],
    round_affine: [[u8; 9]; 15],
    schedule: [u8; 176],
}

fn affine_byte(parameters: &[u8; 9], value: u8) -> u8 {
    let mut result = parameters[0];
    for (bit, p) in parameters[1..].iter().enumerate() {
        if value & (1 << bit) != 0 {
            result ^= p;
        }
    }
    result
}

fn profile_word(profile: &CipherProfile, table_number: usize, index: u8) -> u32 {
    let base = profile.round_base[index as usize];
    let mut word = 0u32;
    for byte in 0..4 {
        let lane = table_number * 4 + byte;
        let value = if lane == 0 { base } else { affine_byte(&profile.round_affine[lane - 1], base) };
        word |= (value as u32) << (byte * 8);
    }
    word
}

fn table_round(profile: &CipherProfile, input: &[u8; 16], round_key: &[u8]) -> [u8; 16] {
    let mut output = [0u8; 16];
    for word in 0..4 {
        let mut value = load32_le(&round_key[word * 4..]);
        for table in 0..4 {
            value ^= profile_word(profile, table, input[(word * 4 + table * 5) & 15]);
        }
        store32_le(&mut output[word * 4..], value);
    }
    output
}

fn final_round(profile: &CipherProfile, input: &[u8; 16], round_key: &[u8]) -> [u8; 16] {
    let mut output = [0u8; 16];
    for (position, (o, k)) in output.iter_mut().zip(round_key).enumerate() {
        let input_position = ((position & 12) + (position & 3) * 5) & 15;
        let table_value = profile.final_map[input[input_position] as usize];
        *o = table_value.wrapping_mul(0x81).wrapping_add(0x7a) ^ k;
    }
    output
}

fn inverse_map_byte(map: &[u8; 256], value: u8) -> u8 {
    map.iter().position(|&m| m == value).unwrap_or(0) as u8
}

/// 長さは 16 の倍数 (呼び出し元は 80 / 32 バイト固定)
fn cipher_cbc(profile: &CipherProfile, output: &mut [u8], input: &[u8], initial_chain: [u8; 16]) {
    debug_assert!(input.len() == output.len() && !input.is_empty() && input.len().is_multiple_of(16));
    let mut chaining = initial_chain;
    for (out_block, in_block) in output.as_chunks_mut::<16>().0.iter_mut().zip(input.as_chunks::<16>().0) {
        let mut state = [0u8; 16];
        for (position, s) in state.iter_mut().enumerate() {
            *s = profile.input_map[in_block[position] as usize] ^ chaining[position] ^ profile.schedule[position];
        }
        for round in 1..10 {
            state = table_round(profile, &state, &profile.schedule[round * 16..]);
        }
        let next = final_round(profile, &state, &profile.schedule[160..]);
        chaining = next;
        for (o, &n) in out_block.iter_mut().zip(&next) {
            *o = profile.output_map[n as usize];
        }
    }
}

fn stage2_cipher(output: &mut [u8], input: &[u8], iv: &[u8; 16]) {
    let initial_chain = iv.map(|v| inverse_map_byte(&STAGE2_PROFILE.output_map, v));
    cipher_cbc(&STAGE2_PROFILE, output, input, initial_chain);
}

// ---------------- expand.c ----------------

/// 元コードは expand() に selector を渡して `selector * 0xb26ed57f == 20` を確かめている。値は固定なのでここで確かめる
const EXPAND_SELECTOR: u32 = 0xaeba51ec;
const _: () = assert!(EXPAND_SELECTOR.wrapping_mul(0xb26ed57f) == 20);

fn transform_hash_chunk(hash: &[u8; 32]) -> [u8; 32] {
    let mut output = [0u8; 32];
    for (o, h) in output.as_chunks_mut::<4>().0.iter_mut().zip(hash.as_chunks::<4>().0) {
        let word = load32_le(h);
        let product = word.wrapping_mul(0xc8180aff);
        let transformed = (word.wrapping_mul(0x6b) as u8 as u32)
            | (((product >> 8).wrapping_mul(0x95) as u8 as u32) << 8)
            | (((product >> 16).wrapping_mul(0x95) as u8 as u32) << 16)
            | (((product >> 24).wrapping_mul(0x95) as u8 as u32) << 24);
        store32_le(o, transformed);
    }
    output
}

fn expand(ciphertext_at_20: &[u8], ciphertext_at_0: &[u8]) -> [u8; 190] {
    let mut work = [0u8; 64];
    for (d, s) in work[..24].iter_mut().zip(ciphertext_at_20) {
        *d = s.wrapping_mul(0x6f);
    }
    for (d, s) in work[24..44].iter_mut().zip(ciphertext_at_0) {
        *d = s.wrapping_mul(0x6f);
    }
    store32_le(&mut work[48..], 12);

    let mut output = [0u8; 190];
    for (iteration, out) in output.chunks_mut(32).enumerate() {
        store32_le(&mut work[44..], iteration as u32);
        // hash() は work を書き換える。次の回はその続きから
        let digest = hash(&mut work);
        let chunk = transform_hash_chunk(&digest);
        out.copy_from_slice(&chunk[..out.len()]);
    }
    output
}

// ---------------- hash.c ----------------

fn encoded_rol(value: W, count: u32) -> W {
    rol(value * Wrapping(0x8fa491df), count & 31)
}

fn hash_preprocess_word(input: u32) -> u32 {
    let input_multiplier = Wrapping(0xa272be3fu32);
    let combine_multiplier = Wrapping(0x7f8631bfu32);
    let byte_multiplier = Wrapping(0xc83bebc7u32);
    let word_bias = Wrapping(0x44e57c7eu32);
    let byte0 = Wrapping(HASH_BYTE_TABLE_0[(input & 0xff) as usize] as u32);
    let mut byte1 = Wrapping(HASH_BYTE_TABLE_1[((input >> 8) & 0xff) as usize] as u32);
    let byte2 = Wrapping(HASH_BYTE_TABLE_2[((input >> 16) & 0xff) as usize] as u32);
    let byte3 = Wrapping(HASH_BYTE_TABLE_3[(input >> 24) as usize] as u32);

    let mut scaled = (((byte0 * Wrapping(0xc9) * Wrapping(0x79)) & Wrapping(0xff)) << 8) * input_multiplier;

    byte1 = (byte1 * Wrapping(0xc9)) & Wrapping(0xff);
    let mut high_mask = !(byte1 * Wrapping(0x79)) | Wrapping(0xff);
    let mut partial = byte1 * byte_multiplier + word_bias + !high_mask * input_multiplier + high_mask * word_bias + scaled;
    scaled = partial * combine_multiplier * Wrapping(0x100) * input_multiplier;

    high_mask = !(byte2 * Wrapping(0x79)) | Wrapping(0xff);
    partial = byte2 * byte_multiplier + word_bias + !high_mask * input_multiplier + high_mask * word_bias + partial + scaled;

    high_mask = !(byte3 * Wrapping(0x79)) | Wrapping(0xff);
    partial = high_mask * word_bias
        + byte3 * byte_multiplier
        + word_bias
        + !high_mask * input_multiplier
        + partial * combine_multiplier * Wrapping(0x100) * input_multiplier
        + partial;

    partial = partial * combine_multiplier * Wrapping(0x100) * input_multiplier + partial;
    (partial * combine_multiplier).0
}

fn hash_byte_index(value: W) -> usize {
    (value.0.wrapping_mul(0xbf) as u8) as usize
}

fn hash_state_to_word(canonical_state_word: u32) -> u32 {
    let state_encode_multiplier = Wrapping(0xc2ed397fu32);
    let input_multiplier = Wrapping(0xa272be3fu32);
    let index_decode = Wrapping(0x7f8631bfu32);
    let index_multiplier = Wrapping(0x5d8d41c1u32);
    let state_multiplier = Wrapping(0xbcb95b41u32);
    let byte_multiplier = Wrapping(0xc83bebc7u32);
    let word_bias = Wrapping(0x44e57c7eu32);
    let rotate_input = Wrapping(0x1e051c21u32);
    let encoded_or_multiplier = Wrapping(0x00f39c82u32);
    let one = Wrapping(1u32);
    let state_word = Wrapping(canonical_state_word) * state_encode_multiplier;

    let mut mapped = Wrapping(HASH_BYTE_TABLE_0[hash_byte_index(state_word * state_multiplier)] as u32);
    mapped = (mapped * Wrapping(0xc9)) & Wrapping(0xff);
    let mut high_mask = !(mapped * Wrapping(0x79)) | Wrapping(0xff);
    let mut combined = state_word * state_multiplier + high_mask * word_bias + mapped * byte_multiplier + word_bias + !high_mask * input_multiplier;
    let mut rotated = encoded_rol(combined * rotate_input, 11);
    rotated *= input_multiplier;

    mapped = Wrapping(HASH_BYTE_TABLE_1[hash_byte_index(rotated)] as u32);
    mapped = (mapped * Wrapping(0xc9)) & Wrapping(0xff);
    high_mask = !(mapped * Wrapping(0x79)) | Wrapping(0xff);
    combined = !high_mask * input_multiplier + mapped * byte_multiplier + word_bias + high_mask * word_bias;
    rotated = encoded_rol(
        (((combined * encoded_or_multiplier - one) | (rotated * encoded_or_multiplier - one)) * input_multiplier + rotated + combined
            - index_multiplier)
            * rotate_input,
        10,
    );

    mapped = Wrapping(HASH_BYTE_TABLE_2[hash_byte_index(rotated * input_multiplier)] as u32);
    high_mask = !(mapped * Wrapping(0x79)) | Wrapping(0xff);
    combined = mapped * byte_multiplier + word_bias + !high_mask * input_multiplier + high_mask * word_bias;
    rotated = encoded_rol((rotated * input_multiplier - combined) * rotate_input, 7);
    (rotated * input_multiplier * index_decode).0
}

/// 64 バイトの work を EDON-R 256 の圧縮関数で 4 回回して 32 バイトを返す。work は最後のブロックで上書きされる
fn hash(work: &mut [u8; 64]) -> [u8; 32] {
    let mut block: [W; 16] = std::array::from_fn(|i| Wrapping(hash_preprocess_word(load32_le(&work[i * 4..]))));
    let mut state = EDONR256_INITIAL_HASH.map(Wrapping);

    for round in 0..4 {
        edonr256_compress(&mut state, &block);
        if round != 3 {
            block = state.map(|s| Wrapping(hash_state_to_word(s.0)));
        }
    }

    for (w, b) in work.as_chunks_mut::<4>().0.iter_mut().zip(&block) {
        store32_le(w, b.0);
    }
    let mut output = [0u8; 32];
    for (o, s) in output.as_chunks_mut::<4>().0.iter_mut().zip(&state[8..]) {
        store32_le(o, (s * Wrapping(0xf46ef4ff)).0);
    }
    output
}

// ---------------- edonr.c ----------------

const EDONR256_INITIAL_HASH: [u32; 16] = [
    0x40414243, 0x44454647, 0x48494a4b, 0x4c4d4e4f, 0x50515253, 0x54555657, 0x58595a5b, 0x5c5d5e5f,
    0x60616263, 0x64656667, 0x68696a6b, 0x6c6d6e6f, 0x70717273, 0x74757677, 0x78797a7b, 0x7c7d7e7f,
];

/// 元コードの Q256 マクロ。出力 z は x / y をすべて読み終えてから書かれるので、同じ配列を渡しても結果は同じ
fn q256(x: &[W; 8], y: &[W; 8]) -> [W; 8] {
    // 前半 (x)
    let t8 = x[0] + x[4];
    let t9 = x[1] + x[7];
    let t12 = t8 + t9;
    let t10 = x[2] + x[3];
    let t11 = x[5] + x[6];
    let t13 = t10 + t11;
    let t0 = Wrapping(0xaaaaaaaa) + t12 + x[2];
    let t1 = rol(t12 + x[3], 4);
    let t2 = rol(t12 + x[6], 8);
    let t3 = rol(t13 + x[7], 13);
    let t4 = rol(x[1] + t13, 17);
    let t5 = rol(t8 + t10 + x[5], 22);
    let t6 = rol(x[0] + t9 + t11, 24);
    let t7 = rol(t13 + x[4], 29);
    let t16 = t0 ^ t4;
    let t17 = t1 ^ t7;
    let t18 = t2 ^ t3;
    let t19 = t5 ^ t6;
    let t8 = t3 ^ t19;
    let t9 = t2 ^ t19;
    let t10 = t18 ^ t5;
    let t11 = t16 ^ t1;
    let t12 = t16 ^ t7;
    let t13 = t17 ^ t6;
    let t14 = t18 ^ t4;
    let t15 = t0 ^ t17;

    // 後半 (y)。t0..t7 と t16..t19 は前半の値を使わないので作り直す
    let t16 = y[0] + y[1];
    let t17 = y[2] + y[5];
    let t20 = t16 + t17;
    let t18 = y[3] + y[4];
    let t22 = t16 + t18;
    let t19 = y[6] + y[7];
    let t21 = t18 + t19;
    let t23 = t17 + t19;
    let t0 = Wrapping(0x55555555) + t20 + y[7];
    let t1 = rol(t22 + y[6], 5);
    let t2 = rol(t20 + y[3], 9);
    let t3 = rol(y[2] + t21, 11);
    let t4 = rol(t22 + y[5], 15);
    let t5 = rol(t23 + y[4], 20);
    let t6 = rol(y[1] + t23, 25);
    let t7 = rol(y[0] + t21, 27);
    let t16 = t0 ^ t1;
    let t17 = t2 ^ t5;
    let t18 = t3 ^ t4;
    let t19 = t6 ^ t7;

    [
        t11 + (t16 ^ t5),
        t12 + (t2 ^ t19),
        t13 + (t16 ^ t3),
        t14 + (t0 ^ t18),
        t15 + (t1 ^ t17),
        t8 + (t18 ^ t6),
        t9 + (t17 ^ t7),
        t10 + (t4 ^ t19),
    ]
}

fn edonr256_compress(hash: &mut [W; 16], block: &[W; 16]) {
    let pick = |idx: [usize; 8]| idx.map(|i| block[i]);
    let lo: [W; 8] = std::array::from_fn(|i| hash[i]);
    let hi: [W; 8] = std::array::from_fn(|i| hash[8 + i]);

    let p16 = q256(&pick([15, 14, 13, 12, 11, 10, 9, 8]), &pick([0, 1, 2, 3, 4, 5, 6, 7]));
    let p24 = q256(&p16, &pick([8, 9, 10, 11, 12, 13, 14, 15]));

    let p16 = q256(&hi, &p16);
    let p24 = q256(&p16, &p24);

    let p16 = q256(&p16, &lo);
    let p24 = q256(&p24, &p16);

    let p16 = q256(&pick([7, 6, 5, 4, 3, 2, 1, 0]), &p16);
    let p24 = q256(&p16, &p24);

    for i in 0..8 {
        hash[i] ^= block[8 + i] ^ p16[i];
        hash[8 + i] ^= block[i] ^ p24[i];
    }
}

