/// `x & 63` の添字
fn ix(value: W) -> usize {
    (value.0 & 63) as usize
}

fn rotate_left_or_ones(value: W, count: u32) -> W {
    if count != 0 { rol(value, count) } else { Wrapping(u32::MAX) }
}

fn rotate_right_or_ones(value: W, count: u32) -> W {
    if count != 0 { Wrapping(value.0.rotate_right(count)) } else { Wrapping(u32::MAX) }
}

fn choose(mask: W, when_set: W, when_clear: W) -> W {
    (mask & when_set) | (!mask & when_clear)
}

fn maj(a: W, b: W, c: W) -> W {
    (a & b) | (a & c) | (b & c)
}

fn fold_word(word: u32) -> u8 {
    let mut folded = word as u8;
    folded = folded.wrapping_add((word >> 8) as u8);
    folded ^= (word >> 16) as u8;
    folded = folded.wrapping_add((word >> 24) as u8);
    folded
}

